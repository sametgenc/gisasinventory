import { test, expect, type Page } from '@playwright/test'
const path = '/api/settings/smtp/'
const settings = { host: 'mail.shipyard.test', port: 587, username: 'service@shipyard.test', password_set: true, use_tls: true, use_ssl: false, from_email: 'service@shipyard.test', is_configured: true, updated_at: null, delivery_mode: 'preview', mfa_enabled: true, mfa_verified_recently: true, reauthentication_required: false }
async function mock(page: Page, patch: Partial<typeof settings> = {}) {
    await page.addInitScript(() => localStorage.setItem('language', 'tr'))
    await page.route('**/_allauth/browser/v1/**', route => route.fulfill({ json: new URL(route.request().url()).pathname.endsWith('/config') ? { status: 200, data: { account: {}, socialaccount: { providers: [] }, mfa: { supported_types: ['totp'] } } } : { status: 200, data: { user: { id: 'admin', username: 'admin', email: 'admin@shipyard.test', role: 'platform_admin', is_superuser: true, has_usable_password: true }, methods: [{ method: 'password', at: Date.now() / 1000 }], flows: [] }, meta: { is_authenticated: true } } }))
    await page.route('**/api/**', route => new URL(route.request().url()).pathname.startsWith('/api/') ? route.fulfill({ json: { count: 0, results: [] } }) : route.continue())
    await page.route(`**${path}`, route => route.fulfill({ json: { ...settings, ...patch } }))
}
test('SMTP preview explains no external mail and MFA setup link; password reveal keyboard works', async ({ page }) => {
    await mock(page, { mfa_enabled: false, mfa_verified_recently: false })
    await page.goto('/platform/settings')
    await expect(page.getByRole('heading', { name: 'E-posta önizleme ortamı' })).toBeVisible()
    await expect(page.getByRole('link', { name: 'Hesap güvenliği' })).toHaveAttribute('href', '/account/authenticators')
    const reveal = page.getByRole('button', { name: /Şifreyi göster/i })
    await reveal.focus()
    await expect(reveal).toBeFocused()
    await reveal.press('Enter')
    await expect(page.locator('#smtp-password')).toHaveAttribute('type', 'text')
    await expect(page.getByRole('button', { name: 'Yok', exact: true })).toHaveCount(0)
})
test('test email blocks duplicates and dismissal; preview success stays visible without delivery claim', async ({ page }) => {
    await mock(page)
    let sent = 0
    let release = () => {}
    const wait = new Promise<void>(resolve => { release = resolve })
    await page.route(`**${path}test/`, async route => { sent += 1; expect(route.request().postDataJSON()).toEqual({ email: 'preview@shipyard.test' }); await wait; await route.fulfill({ json: { detail: 'preview', delivery_mode: 'preview' } }) })
    await page.goto('/platform/settings')
    await page.getByRole('button', { name: 'Test e-postası gönder', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('textbox').fill('preview@shipyard.test')
    await dialog.getByRole('button', { name: 'Test e-postası gönder', exact: true }).click()
    await expect(dialog.getByRole('button', { name: 'Test e-postası gönder', exact: true })).toBeDisabled()
    await page.keyboard.press('Escape')
    await expect(dialog).toBeVisible()
    expect(sent).toBe(1)
    release()
    await expect(dialog.getByRole('status')).toHaveText('Test e-postası önizlemesi oluşturuldu. Dışarıya e-posta gönderilmedi.')
    await page.waitForTimeout(5100)
    await expect(dialog.getByRole('status')).toBeVisible()
    expect(sent).toBe(1)
})
